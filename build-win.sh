#!/usr/bin/env bash
# Build the Windows package zip. Run from repo root.
# v26+: mail-fleet-panel.exe is a Node SEA single-file exe (double-click to run,
# no vbs). Exe-adjacent layout: web/dist + data/worker-dist (+ data/official-dist
# when available). Keeps /tmp/sea/winpkg as the packaging base.
set -e
cd "$(dirname "$0")"

echo "[1/5] building web dist..."
(cd web && npm run build)

echo "[2/5] bundling server + applying patches (SEA entry)..."
mkdir -p pkg
(cd server && node -e "const es=require('/tmp/postject/node_modules/esbuild'); es.build({entryPoints:['src/index.js'],bundle:true,platform:'node',format:'cjs',outfile:'../pkg/sea-entry.cjs',supported:{'import-meta':false},inject:['../tools/dirname-shim.js'],define:{'process.env.PANEL_SEA':'\"1\"','import.meta.url':'\"file:///app/index.js\"'},logLevel:'silent'})")
python3 tools/patch-panel.py pkg/sea-entry.cjs

echo "[3/5] staging worker deploy bundle (data/worker-dist)..."
# worker.js: wrangler dry-run bundle of cloud-mail mail-worker (ESM, self-contained);
# static assets: mail-worker's built frontend. Refresh the repo copy (docker build
# context) and the winpkg copy from the same build.
# The shipped data dir must contain ONLY deploy packages: a stale panel.db from test
# runs locked users out (undecryptable credentials under the app's PANEL_SECRET,
# phantom test sites) — the "手动装可以，做成应用就有问题" bug.
(cd /cloudmail/cloud-mail/mail-worker && npx wrangler deploy --dry-run --outdir /tmp/worker-bundle >/dev/null)
rm -rf data/worker-dist /tmp/sea/winpkg/data/worker-dist
mkdir -p data/worker-dist /tmp/sea/winpkg/data/worker-dist
rm -rf /tmp/sea/winpkg/data/bundles /tmp/sea/winpkg/data/panel.db /tmp/sea/winpkg/data/panel.db-wal /tmp/sea/winpkg/data/panel.db-shm
cp /tmp/worker-bundle/index.js data/worker-dist/worker.js
cp -r /cloudmail/cloud-mail/mail-worker/dist/. data/worker-dist/
cp -r data/worker-dist/. /tmp/sea/winpkg/data/worker-dist/
test -f /tmp/sea/winpkg/data/worker-dist/worker.js
test -f /tmp/sea/winpkg/data/worker-dist/index.html
# official deploy package if previously built (optional in local builds)
if [ -d data/official-dist ] && [ -f data/official-dist/worker.js ]; then
  rm -rf /tmp/sea/winpkg/data/official-dist
  cp -r data/official-dist /tmp/sea/winpkg/data/official-dist
  echo "  official-dist included"
fi

echo "[4/5] building SEA single-file exe..."
# blob must be generated by the same node major as the exe runtime
N22=/tmp/sea/node-v22.20.0-linux-x64/bin/node
[ -x "$N22" ] || { echo "node22 linux missing — download https://nodejs.org/dist/v22.20.0/node-v22.20.0-linux-x64.tar.xz to /tmp/sea"; exit 1; }
"$N22" --experimental-sea-config tools/sea-config.json
cp /tmp/sea/node-v22.20.0-win-x64/node.exe /tmp/sea/winpkg/mail-fleet-panel.exe
node /tmp/postject/node_modules/postject/dist/cli.js /tmp/sea/winpkg/mail-fleet-panel.exe NODE_SEA_BLOB sea-prep.blob \
  --sentinel-fuse NODE_SEA_FUSE_fce680ab2cc467b6e072b8b5df1996b2 --overwrite
# GUI subsystem: no console window on double-click (logs stay in the void;
# check data/ or the browser UI instead)
python3 tools/patch-pe-gui.py /tmp/sea/winpkg/mail-fleet-panel.exe --inplace
rm -f /tmp/sea/winpkg/panel.cjs /tmp/sea/winpkg/启动面板.vbs /tmp/sea/winpkg/停止面板.vbs /tmp/sea/winpkg/后台启动面板.vbs

echo "[5/5] syncing web dist + zipping..."
rm -f /tmp/sea/winpkg/sea-entry.cjs /tmp/sea/winpkg/sea-prep.blob
rm -rf /tmp/sea/winpkg/web/dist
cp -r web/dist /tmp/sea/winpkg/web/dist
cp tools/win-README.txt /tmp/sea/winpkg/README.txt
python3 - <<'EOF'
import zipfile, os
src='/tmp/sea/winpkg'; out='/cloudmail/mail-fleet-panel-win.zip'
with zipfile.ZipFile(out,'w',zipfile.ZIP_DEFLATED) as z:
    for root,_,files in os.walk(src):
        for f in files:
            p=os.path.join(root,f)
            z.write(p, os.path.relpath(p,src))
# sanity: packaged UI must be the current one
z = zipfile.ZipFile(out)
d = ''.join(z.read(n).decode('utf8','ignore') for n in z.namelist() if n.endswith('.js'))
assert '原版界面内嵌' not in d, 'zip still contains OLD iframe UI!'
assert '复制密码' in d, 'zip missing NEW console UI!'
# SEA exe must be present and contain the blob
assert 'mail-fleet-panel.exe' in z.namelist(), 'SEA exe missing!'
exe = z.read('mail-fleet-panel.exe')
assert b'NODE_SEA_FUSE_fce680ab2cc467b6e072b8b5df1996b2' in exe, 'SEA fuse missing in exe!'
# deploy bundle must ship (this was the "你没有打包" bug)
z.read('data/worker-dist/worker.js')
z.read('data/worker-dist/index.html')
assert any(n.startswith('data/worker-dist/assets/') for n in z.namelist()), 'worker-dist assets missing!'
# the app zip must NOT ship a used database (test data + undecryptable creds)
assert not any(n.startswith('data/panel.db') for n in z.namelist()), 'stale panel.db shipped!'
assert not any(n.startswith('data/bundles') for n in z.namelist()), 'stale bundles shipped!'
print('OK ->', out, os.path.getsize(out))
EOF
